//! The 2026-10-28 MiQi repair-loop gap, through the actual CLI.
//!
//! A check-failure finding is repaired by editing only the check's own test, and
//! the re-check sees the check pass. Before this behaviour existed, that closed
//! the finding and the panel reported the repair as done; the repair contract's
//! "changing only the test or assertion" clause was text nobody enforced.
//!
//! These tests use a real Cargo fixture and the real commands: `sure repair`
//! records the finding, the MiQi write event is ingested through `sure hook
//! ingest` (the same path the MiQi plugin uses), the test is rewritten, and
//! `sure recheck` compares. Both the guard and its control are measured, so a
//! guard that simply kept every check-failure finding open would fail the
//! second test.

#![allow(clippy::unwrap_used, clippy::expect_used, clippy::panic)]

use std::io::Write;
use std::path::{Path, PathBuf};
use std::process::{Command, Output, Stdio};

const SURE: &str = env!("CARGO_BIN_EXE_sure");

fn write(path: &Path, text: &str) {
    std::fs::write(path, text)
        .unwrap_or_else(|error| panic!("could not write {}: {error}", path.display()));
}

/// A Cargo project whose one integration test expects the product's value to be
/// two while the product returns one: `cargo test` fails, and the failure is a
/// deterministic check SURE ran itself.
///
/// The test lives in `tests/` rather than beside the product code so that the
/// path itself says "test" to [`sure_core::candidate_context`] — the same
/// reading the guard uses. A unit-test module inside `src/lib.rs` would be a
/// production path by classification, and neither test could measure the guard.
///
/// Returns the project, a store and a settings file, all of this test's own.
fn fixture(name: &str) -> (PathBuf, PathBuf, PathBuf) {
    let root = sure_testkit::scratch::directory("sure cli test only repair", name);
    let project = root.join("project");
    let store = root.join("store");
    std::fs::create_dir_all(project.join("src")).expect("the project directory");
    std::fs::create_dir_all(project.join("tests")).expect("the test directory");
    std::fs::create_dir_all(&store).expect("the store directory");

    write(
        &project.join("Cargo.toml"),
        "[package]\nname = 'sure_test_only_fixture'\nversion = '0.1.0'\nedition = '2021'\n\
         [lib]\npath = 'src/lib.rs'\n\n[workspace]\n",
    );
    // A pre-existing lockfile keeps Cargo from changing the project state during
    // the run; offline mode keeps the fixture from touching the network.
    write(
        &project.join("Cargo.lock"),
        "# This file is automatically @generated by Cargo.\n\
         # It is not intended for manual editing.\nversion = 4\n\n\
         [[package]]\nname = \"sure_test_only_fixture\"\nversion = \"0.1.0\"\n",
    );
    write(
        &project.join("src").join("lib.rs"),
        "pub fn value() -> i32 {\n    1\n}\n",
    );
    write(
        &project.join("tests").join("works.rs"),
        "#[test]\nfn value_is_two() {\n    assert_eq!(sure_test_only_fixture::value(), 2);\n}\n",
    );

    let settings = root.join("user-settings.yaml");
    // `cargo test` is refused under `allow_network: false` because Cargo may
    // fetch; the fixture has its lockfile and Cargo runs with
    // `CARGO_NET_OFFLINE=true`, so allowing network here runs nothing online.
    write(
        &settings,
        "execution:\n  mode: host_confirmed\n  allow_network: true\n",
    );
    (project, store, settings)
}

fn run(store: &Path, settings: &Path, args: &[&str]) -> Output {
    Command::new(SURE)
        .arg("--store-dir")
        .arg(store)
        .arg("--settings-file")
        .arg(settings)
        .args(args)
        .env("CARGO_NET_OFFLINE", "true")
        .env_remove("CARGO_TARGET_DIR")
        .stdin(Stdio::null())
        .output()
        .expect("the CLI starts")
}

fn frame(output: &Output) -> serde_json::Value {
    let stdout = String::from_utf8_lossy(&output.stdout);
    serde_json::from_str(stdout.trim()).unwrap_or_else(|error| {
        panic!(
            "`sure` printed no frame: {error}\n{stdout}\n{}",
            String::from_utf8_lossy(&output.stderr)
        )
    })
}

/// Ingest a completed write the way the MiQi plugin does.
fn ingest_write(store: &Path, settings: &Path, project: &Path, path: &Path) {
    let payload = serde_json::json!({
        "event": "PostToolUse",
        "harness_session_id": "test-only-repair",
        "timestamp_utc": "2026-10-28T12:00:00Z",
        "source": "miqi",
        "tool": "write_file",
        "path": path.to_string_lossy(),
        "project_root": project.to_string_lossy(),
    })
    .to_string();

    let mut command = Command::new(SURE);
    command
        .arg("--store-dir")
        .arg(store)
        .arg("--settings-file")
        .arg(settings)
        .args(["--format", "json", "hook", "ingest", "--source", "miqi"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped());
    let mut child = command.spawn().expect("the hook process starts");
    child
        .stdin
        .take()
        .expect("the pipe")
        .write_all(payload.as_bytes())
        .expect("the event is written to stdin");
    let output = child.wait_with_output().expect("the hook process exits");
    assert!(
        output.status.success(),
        "`sure hook ingest` refused the event:\n{}",
        String::from_utf8_lossy(&output.stderr)
    );
}

/// The repair run's record: at least one finding and its repair contract.
fn repair(store: &Path, settings: &Path, project: &Path) -> serde_json::Value {
    let before = run(
        store,
        settings,
        &["--format", "json", "repair", &project.to_string_lossy()],
    );
    assert_eq!(
        before.status.code(),
        Some(1),
        "`sure repair` on a failing project returned {:?}:\n{}\n{}",
        before.status.code(),
        String::from_utf8_lossy(&before.stdout),
        String::from_utf8_lossy(&before.stderr)
    );
    let frame = frame(&before);
    let repairs = frame["details"]["repairs"]
        .as_array()
        .unwrap_or_else(|| panic!("`sure repair` answered with no repairs array: {frame}"));
    assert!(
        !repairs.is_empty(),
        "the failing test produced no repair contract: {frame}"
    );
    frame
}

#[test]
fn a_repair_that_edited_only_the_test_does_not_close_the_finding() {
    let (project, store, settings) = fixture("edits-the-test");
    let repaired = repair(&store, &settings, &project);
    let title = repaired["details"]["repairs"][0]["problem"]
        .as_str()
        .expect("the contract names the problem")
        .to_owned();

    // The repair a coding agent made on 2026-10-28: the assertion now agrees
    // with the product code. Nothing in the product changed.
    let test_file = project.join("tests").join("works.rs");
    write(
        &test_file,
        "#[test]\nfn value_is_two() {\n    assert_eq!(sure_test_only_fixture::value(), 1);\n}\n",
    );
    ingest_write(&store, &settings, &project, &test_file);

    let after = run(
        &store,
        &settings,
        &["--format", "json", "recheck", &project.to_string_lossy()],
    );
    let recheck = frame(&after);
    let lifecycle = &recheck["details"]["lifecycle"];
    assert!(
        lifecycle.is_object(),
        "`sure recheck` reported no comparison: {recheck}"
    );
    assert_eq!(
        lifecycle["closed"].as_array().map(Vec::len),
        Some(0),
        "a test-only repair closed the finding: {recheck}"
    );
    let still_open = lifecycle["still_open"]
        .as_array()
        .unwrap_or_else(|| panic!("no still_open list: {recheck}"));
    assert!(
        still_open
            .iter()
            .any(|finding| finding["title"].as_str() == Some(title.as_str())),
        "the finding the repair was about is not reported open: {recheck}"
    );

    // The stage says why in its own words, rather than leaving a reader to
    // infer it from a count.
    let stages = recheck["details"]["stages"]
        .as_array()
        .unwrap_or_else(|| panic!("no stages array: {recheck}"));
    let recheck_stage = stages
        .iter()
        .find(|stage| stage["stage"] == "recheck" || stage["number"] == 12)
        .unwrap_or_else(|| panic!("stage 12 is missing from the frame: {recheck}"));
    let detail = recheck_stage["detail"]
        .as_str()
        .unwrap_or_else(|| panic!("stage 12 carried no detail: {recheck_stage}"));
    assert!(
        detail.contains("test file"),
        "stage 12 does not say the only recorded change was a test: {detail}"
    );
}

#[test]
fn a_repair_that_changed_the_product_code_closes_the_finding() {
    let (project, store, settings) = fixture("changes-the-product");
    let repaired = repair(&store, &settings, &project);
    let title = repaired["details"]["repairs"][0]["problem"]
        .as_str()
        .expect("the contract names the problem")
        .to_owned();

    // The real fix: the product now returns what the test expects.
    let product = project.join("src").join("lib.rs");
    write(&product, "pub fn value() -> i32 {\n    2\n}\n");
    ingest_write(&store, &settings, &project, &product);

    let after = run(
        &store,
        &settings,
        &["--format", "json", "recheck", &project.to_string_lossy()],
    );
    let recheck = frame(&after);
    let lifecycle = &recheck["details"]["lifecycle"];
    let closed = lifecycle["closed"]
        .as_array()
        .unwrap_or_else(|| panic!("`sure recheck` reported no comparison: {recheck}"));
    assert!(
        closed
            .iter()
            .any(|finding| finding["title"].as_str() == Some(title.as_str())),
        "a real product-code fix did not close the finding: {recheck}"
    );
    assert!(
        lifecycle["still_open"]
            .as_array()
            .is_some_and(Vec::is_empty),
        "a real fix left the finding open: {recheck}"
    );
}
